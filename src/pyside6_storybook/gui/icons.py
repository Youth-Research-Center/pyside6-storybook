"""Bundled vector icons for the gallery's chrome, tinted from the palette.

The bundle ``resources/icons/icon_bundle.json`` is generated by ``scripts/icons/build_icon_bundle.py`` from
``resources/icons/icon_manifest.toml``; the gallery only reads the committed file and never downloads icons. To add an icon, edit the
manifest and rerun the script (see AGENTS.md).
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from enum import Enum
from functools import lru_cache
from importlib import resources

import shiboken6
from PySide6.QtCore import QByteArray, QRectF
from PySide6.QtGui import QAction, QColor, QGuiApplication, QIcon, QPainter, QPalette, QPixmap
from PySide6.QtSvg import QSvgRenderer
from PySide6.QtWidgets import QAbstractButton, QApplication

DEFAULT_ICON_SIZE = 16
_MANIFEST_HINT = "src/pyside6_storybook/resources/icons/icon_manifest.toml"
_WEIGHT = "regular"


class IconRole(Enum):
    """Which palette role tints an icon; each value is that ``QPalette.ColorRole``."""

    TEXT = QPalette.ColorRole.WindowText
    MUTED = QPalette.ColorRole.PlaceholderText
    ACCENT = QPalette.ColorRole.Highlight
    ON_ACCENT = QPalette.ColorRole.HighlightedText


@lru_cache(maxsize=1)
def _load_bundle() -> dict:
    text = resources.files("pyside6_storybook.resources").joinpath("icons", "icon_bundle.json").read_text(encoding="utf-8")
    return json.loads(text)


def icon_svg(name: str) -> str:
    """Return the bundled SVG markup of an icon (it uses ``currentColor`` for tinting).

    Args:
        name: Icon name as listed in ``icon_manifest.toml``.

    Returns:
        The SVG document.

    Raises:
        KeyError: If the icon is not in the bundle; the message names the manifest and the script that regenerates the bundle.
    """
    icons = _load_bundle()["icons"]
    if name not in icons:
        raise KeyError(f"Icon '{name}' is not bundled; add it to {_MANIFEST_HINT} and run scripts/icons/build_icon_bundle.py")
    return icons[name]["weights"][_WEIGHT]


def _device_pixel_ratio() -> float:
    screen = QGuiApplication.primaryScreen()
    return screen.devicePixelRatio() if screen is not None else 1.0


@lru_cache(maxsize=256)
def _render_pixmap(name: str, color: str, size: int, ratio: float) -> QPixmap:
    """Render one tinted pixmap; the cache is keyed on every argument, so a new colour or pixel ratio renders again.

    The cached pixmap is shared between icons (``QPixmap`` is implicitly shared) and must not be painted on by callers.
    """
    tint = QColor(color)
    if not tint.isValid():
        raise ValueError(f"Invalid icon colour: {color!r}")
    svg = icon_svg(name).replace("currentColor", tint.name())
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pixmap = QPixmap(round(size * ratio), round(size * ratio))
    pixmap.setDevicePixelRatio(ratio)
    pixmap.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pixmap)
    try:
        painter.setOpacity(tint.alphaF())
        renderer.render(painter, QRectF(0, 0, size, size))
    finally:
        painter.end()
    return pixmap


def clear_icon_cache() -> None:
    """Drop every cached icon render, for example after the primary screen's pixel ratio changed, and between tests."""
    _render_pixmap.cache_clear()


def build_icon(
    name: str,
    color: str,
    *,
    size: int = DEFAULT_ICON_SIZE,
    disabled_color: str | None = None,
    selected_color: str | None = None,
) -> QIcon:
    """Render a bundled icon tinted with ``color``, and optionally another colour when disabled or selected.

    Every call returns a new ``QIcon``; the pixmaps behind it come from a cache keyed by name, colour, size and pixel ratio.

    Args:
        name: Icon name as listed in ``icon_manifest.toml``.
        color: Any colour ``QColor`` understands, such as ``#rrggbb`` or ``#aarrggbb``; the alpha channel makes the icon translucent.
        size: Logical pixel size of the square icon.
        disabled_color: Colour for ``QIcon.Mode.Disabled``; Qt greys the icon itself when omitted.
        selected_color: Colour for ``QIcon.Mode.Selected`` (an icon on a selected row); Qt derives it when omitted.

    Returns:
        The icon.

    Raises:
        KeyError: If the icon is not bundled.
        ValueError: If a colour is invalid.
    """
    ratio = _device_pixel_ratio()
    icon = QIcon()
    icon.addPixmap(_render_pixmap(name, color, size, ratio), QIcon.Mode.Normal)
    if disabled_color is not None:
        icon.addPixmap(_render_pixmap(name, disabled_color, size, ratio), QIcon.Mode.Disabled)
    if selected_color is not None:
        icon.addPixmap(_render_pixmap(name, selected_color, size, ratio), QIcon.Mode.Selected)
    return icon


def palette_icon(name: str, *, role: IconRole = IconRole.TEXT, palette: QPalette | None = None, size: int = DEFAULT_ICON_SIZE) -> QIcon:
    """Render a bundled icon tinted from a palette role.

    The Normal state uses the role's Active colour, the Disabled state the role's colour in the Disabled group, and the Selected state
    ``HighlightedText``.

    Args:
        name: Icon name as listed in ``icon_manifest.toml``.
        role: The palette role that tints the icon.
        palette: The palette to read; the application's palette when omitted.
        size: Logical pixel size of the square icon.

    Returns:
        The icon.

    Raises:
        KeyError: If the icon is not bundled.
    """
    source = palette if palette is not None else QApplication.palette()
    return build_icon(
        name,
        source.color(QPalette.ColorGroup.Active, role.value).name(QColor.NameFormat.HexArgb),
        size=size,
        disabled_color=source.color(QPalette.ColorGroup.Disabled, role.value).name(QColor.NameFormat.HexArgb),
        selected_color=source.color(QPalette.ColorGroup.Active, QPalette.ColorRole.HighlightedText).name(QColor.NameFormat.HexArgb),
    )


@dataclass(frozen=True)
class _Binding:
    """An action or button bound to a bundled icon."""

    target: QAction | QAbstractButton
    name: str
    role: IconRole


class ActionIcons:
    """Registry of actions and buttons whose bundled icons follow the palette.

    Call ``retint()`` when the palette changes; the gallery window does it from its ``changeEvent``.
    """

    def __init__(self, *, size: int = DEFAULT_ICON_SIZE) -> None:
        """Create an empty registry.

        Args:
            size: Logical pixel size of the square icons.
        """
        self._logger = logging.getLogger(self.__class__.__name__)
        self._size = size
        self._bound: list[_Binding] = []

    def bind(self, target: QAction | QAbstractButton, name: str, *, role: IconRole = IconRole.TEXT) -> None:
        """Set ``target``'s icon now and render it again on every ``retint()``.

        Args:
            target: The action or button that gets the icon.
            name: Icon name as listed in ``icon_manifest.toml``.
            role: The palette role that tints the icon.

        Raises:
            KeyError: If the icon is not bundled.
        """
        binding = _Binding(target, name, role)
        self._apply(binding, None)
        self._bound.append(binding)

    def retint(self, palette: QPalette | None = None) -> None:
        """Render every bound icon again from a palette, dropping targets that no longer exist.

        Args:
            palette: The palette to read; the application's palette when omitted.
        """
        alive = [binding for binding in self._bound if shiboken6.isValid(binding.target)]
        if len(alive) != len(self._bound):
            self._logger.debug("Dropped %d deleted icon targets", len(self._bound) - len(alive))
        self._bound = alive
        for binding in alive:
            self._apply(binding, palette)

    def _apply(self, binding: _Binding, palette: QPalette | None) -> None:
        binding.target.setIcon(palette_icon(binding.name, role=binding.role, palette=palette, size=self._size))


__all__ = ["ActionIcons", "IconRole", "build_icon", "clear_icon_cache", "icon_svg", "palette_icon"]
